-- Profiel per gebruiker: naam (gelijk aan de administrateursnaam) en rol.
create table if not exists public.profielen (
  id uuid primary key references auth.users (id) on delete cascade,
  naam text not null,
  rol text not null default 'collega' check (rol in ('beheer', 'collega'))
);

-- Stamgegevens per klant. Alleen beheer mag wijzigen.
create table if not exists public.klanten (
  id bigint generated by default as identity primary key,
  naam text not null,
  status text not null default 'Actief' check (status in ('Actief', 'Opgezegd', 'Gestopt')),
  administrateur text,
  verwerking text not null default 'maand' check (verwerking in ('maand', 'kwartaal')),
  bank text,
  boekhoudpakket text,
  altijd_up2date boolean not null default false,
  rechtsvorm text,
  pakket text,
  facturen integer,
  btw_regime text not null default 'Normaal',
  btw_per_maand boolean not null default false,
  personenauto boolean not null default false,
  bestelauto boolean not null default false,
  km_registratie boolean not null default false,
  verklaring_uzgb boolean not null default false,
  km_uzgb_splitsen boolean not null default false,
  motor boolean not null default false,
  fiets boolean not null default false,
  pand text,
  bijzonderheden text,
  email text,
  voornaam text,
  achternaam text,
  btw_nummer text,
  btw_id text,
  google_review boolean not null default false,
  vanaf_jaar integer,
  vanaf_kwartaal integer check (vanaf_kwartaal between 1 and 4),
  gestopt_jaar integer,
  einde jsonb,
  gewijzigd_op timestamptz not null default now()
);

-- Voortgang per klant per jaar. Iedereen mag afvinken.
-- Een lege waarde (null) betekent: niet van toepassing.
-- controle_vj, jaarwerk_vj en ib_vj gaan over het vorige jaar (in 2026 dus over 2025).
create table if not exists public.voortgang (
  klant_id bigint not null references public.klanten (id) on delete cascade,
  jaar integer not null,
  m1 boolean, m2 boolean, m3 boolean, m4 boolean, m5 boolean, m6 boolean,
  m7 boolean, m8 boolean, m9 boolean, m10 boolean, m11 boolean, m12 boolean,
  btw1 boolean, btw2 boolean, btw3 boolean, btw4 boolean,
  controle_q2 boolean, controle_q3 boolean,
  controle_vj boolean, jaarwerk_vj boolean, ib_vj boolean,
  notities text,
  gewijzigd_op timestamptz not null default now(),
  primary key (klant_id, jaar)
);
-- Wacht op klant: per periode, bijv. {"m10": true, "btw3": true}
alter table public.voortgang add column if not exists wacht jsonb not null default '{}'::jsonb;

-- Instellingen voor het hele team (huidig werkjaar, peilmaand).
create table if not exists public.instellingen (
  sleutel text primary key,
  waarde jsonb
);
insert into public.instellingen (sleutel, waarde) values ('huidig_jaar', '2026'::jsonb) on conflict (sleutel) do nothing;

-- Historie: wie heeft wat wanneer gedaan.
create table if not exists public.historie (
  id bigint generated by default as identity primary key,
  klant_id bigint references public.klanten (id) on delete cascade,
  wie text not null,
  wat text not null,
  wanneer timestamptz not null default now()
);
create index if not exists historie_klant_idx on public.historie (klant_id, wanneer desc);

-- Tijdstip van laatste wijziging automatisch bijhouden.
create or replace function public.zet_gewijzigd_op() returns trigger language plpgsql as $$
begin new.gewijzigd_op := now(); return new; end $$;
drop trigger if exists klanten_gewijzigd on public.klanten;
create trigger klanten_gewijzigd before update on public.klanten for each row execute function public.zet_gewijzigd_op();
drop trigger if exists voortgang_gewijzigd on public.voortgang;
create trigger voortgang_gewijzigd before update on public.voortgang for each row execute function public.zet_gewijzigd_op();

-- ---------------------------------------------------------------
-- Rechten (Row Level Security)
-- Klantgegevens zijn alleen bereikbaar na wachtwoord EN code uit de authenticator-app (aal2).
-- ---------------------------------------------------------------
create or replace function public.tweestaps() returns boolean
language sql stable as $$
  select coalesce(auth.jwt() ->> 'aal', '') = 'aal2';
$$;
create or replace function public.is_beheer() returns boolean
language sql stable security definer set search_path = public as $$
  select public.tweestaps() and exists (select 1 from public.profielen where id = auth.uid() and rol = 'beheer');
$$;
create or replace function public.is_medewerker() returns boolean
language sql stable security definer set search_path = public as $$
  select public.tweestaps() and exists (select 1 from public.profielen where id = auth.uid());
$$;

alter table public.profielen enable row level security;
alter table public.klanten enable row level security;
alter table public.voortgang enable row level security;
alter table public.historie enable row level security;
alter table public.instellingen enable row level security;

drop policy if exists "profielen lezen" on public.profielen;
create policy "profielen lezen" on public.profielen for select to authenticated using (public.is_medewerker() or id = auth.uid());
drop policy if exists "profielen beheren" on public.profielen;
create policy "profielen beheren" on public.profielen for all to authenticated using (public.is_beheer()) with check (public.is_beheer());

drop policy if exists "klanten lezen" on public.klanten;
create policy "klanten lezen" on public.klanten for select to authenticated using (public.is_medewerker());
drop policy if exists "klanten beheren" on public.klanten;
create policy "klanten beheren" on public.klanten for all to authenticated using (public.is_beheer()) with check (public.is_beheer());

drop policy if exists "voortgang lezen" on public.voortgang;
create policy "voortgang lezen" on public.voortgang for select to authenticated using (public.is_medewerker());
drop policy if exists "voortgang toevoegen" on public.voortgang;
create policy "voortgang toevoegen" on public.voortgang for insert to authenticated with check (public.is_medewerker());
drop policy if exists "voortgang wijzigen" on public.voortgang;
create policy "voortgang wijzigen" on public.voortgang for update to authenticated using (public.is_medewerker()) with check (public.is_medewerker());
drop policy if exists "voortgang verwijderen" on public.voortgang;
create policy "voortgang verwijderen" on public.voortgang for delete to authenticated using (public.is_beheer());

drop policy if exists "historie lezen" on public.historie;
create policy "historie lezen" on public.historie for select to authenticated using (public.is_medewerker());
drop policy if exists "historie schrijven" on public.historie;
create policy "historie schrijven" on public.historie for insert to authenticated with check (public.is_medewerker());

drop policy if exists "instellingen lezen" on public.instellingen;
create policy "instellingen lezen" on public.instellingen for select to authenticated using (public.is_medewerker());
drop policy if exists "instellingen beheren" on public.instellingen;
create policy "instellingen beheren" on public.instellingen for all to authenticated using (public.is_beheer()) with check (public.is_beheer());

-- Geen toegang voor niet-ingelogde bezoekers.
revoke all on public.profielen, public.klanten, public.voortgang, public.historie, public.instellingen from anon;

